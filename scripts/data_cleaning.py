"""
Data cleaning for the crop production dataset.

Reads the raw CSV, applies cleaning rules, and writes a SEPARATE cleaned file.
The raw input is never modified, so the pipeline can be re-run safely.

Usage:
    py scripts/data_cleaning.py

Expected layout:
    data/raw/Crop Production data.csv      <- download it yourself, not in Git
    data/processed/crop_production_clean.csv <- generated by this script
"""

from pathlib import Path

import pandas as pd

RAW_FILE = Path("data/raw/Crop Production data.csv")
CLEAN_FILE = Path("data/processed/crop_production_clean.csv")

REQUIRED_COLUMNS = {"area", "production"}


def load_raw(path: Path) -> pd.DataFrame:
    """Read the raw dataset, failing with a clear message if it is missing."""
    if not path.exists():
        raise FileNotFoundError(
            f"Raw dataset not found at '{path}'.\n"
            "Download 'Crop Production data.csv' into data/raw/ first. "
            "See the README for the source link."
        )
    return pd.read_csv(path)


def clean(df: pd.DataFrame) -> pd.DataFrame:
    """Standardize column names, drop invalid rows, and add the yield KPI."""
    df = df.copy()

    # Standardize: lowercase, strip, spaces -> underscores
    df.columns = [str(c).strip().lower().replace(" ", "_") for c in df.columns]

    missing = REQUIRED_COLUMNS - set(df.columns)
    if missing:
        raise ValueError(
            f"Missing required columns: {sorted(missing)}. "
            f"Columns found: {list(df.columns)}"
        )

    # Drop rows missing the values we depend on
    df = df.dropna(subset=list(REQUIRED_COLUMNS))

    # Keep only physically meaningful records
    df = df[(df["area"] > 0) & (df["production"] > 0)]

    # Yield per hectare: production divided by area
    df["yield_per_hectare"] = df["production"] / df["area"]

    return df


def save(df: pd.DataFrame, path: Path) -> None:
    """Write the cleaned dataset, creating parent folders if needed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)


def main() -> None:
    raw = load_raw(RAW_FILE)
    print(f"Loaded {len(raw):,} rows and {len(raw.columns)} columns")

    cleaned = clean(raw)
    removed = len(raw) - len(cleaned)
    print(f"Removed {removed:,} invalid rows, kept {len(cleaned):,}")

    save(cleaned, CLEAN_FILE)
    print(f"Saved cleaned data to '{CLEAN_FILE}'")


if __name__ == "__main__":
    main()
